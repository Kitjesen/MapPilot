#!/usr/bin/env bash
# Prepare an isolated GStreamer 1.28 + gst-plugin-webrtc 0.15 toolchain.
# This is a build dependency helper only. It does not install a service and
# does not alter ProductControl or the system GStreamer installation.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
LOCK="${ROOT}/scripts/build/locks/video.json"
PREFIX="${ROOT}/build/deps/video/prefix"
# Keep source checkout and compiler intermediates on persistent Linux storage
# when invoked from WSL. The installed prefix remains under build/.
CACHE_ROOT="${XDG_CACHE_HOME:-${HOME}/.cache}/lingtu/video"
WORK_ROOT="${LINGTU_VIDEO_WORK_ROOT:-${CACHE_ROOT}/work}"
SRC="${WORK_ROOT}/src"
BUILD="${WORK_ROOT}/build"
IFS=$'\t' read -r GST_VERSION GST_COMMIT RS_VERSION RS_COMMIT MESON_VERSION NINJA_VERSION RUST_VERSION CARGO_C_VERSION < <(
  python3 -c 'import json,sys; d=json.load(open(sys.argv[1])); print("\t".join((d["gstreamer"]["version"], d["gstreamer"]["commit"], d["gst_plugin_webrtc"]["version"], d["gst_plugin_webrtc"]["commit"], d["build_tools"]["meson"], d["build_tools"]["ninja"], d["build_tools"]["rust"], d["build_tools"]["cargo_c"])))' "${LOCK}"
)

MULTIARCH="$(gcc -print-multiarch 2>/dev/null || true)"
if [[ -z "${MULTIARCH}" ]] && command -v dpkg-architecture >/dev/null 2>&1; then
  MULTIARCH="$(dpkg-architecture -qDEB_HOST_MULTIARCH)"
fi
if [[ -z "${MULTIARCH}" ]]; then
  echo "Cannot determine the native compiler multiarch for camera video." >&2
  exit 2
fi
case "$(uname -m)" in
  amd64|x86_64) RUNTIME_ARCH=x86_64 ;;
  arm64|aarch64) RUNTIME_ARCH=aarch64 ;;
  *) RUNTIME_ARCH="$(uname -m)" ;;
esac

write_runtime_metadata() {
  local env_file="${PREFIX}/env.sh"
  cat > "${env_file}" <<EOF
# Generated by scripts/build/prepare_camera_video.sh. Relocatable after install.
_lingtu_video_prefix="\$(cd "\$(dirname "\${BASH_SOURCE[0]}")" && pwd)"
_lingtu_video_multiarch="${MULTIARCH}"
export PATH="\${_lingtu_video_prefix}/bin:\${PATH}"
export PKG_CONFIG_PATH="\${_lingtu_video_prefix}/lib/\${_lingtu_video_multiarch}/pkgconfig:\${_lingtu_video_prefix}/lib/pkgconfig\${PKG_CONFIG_PATH:+:\${PKG_CONFIG_PATH}}"
export LD_LIBRARY_PATH="\${_lingtu_video_prefix}/lib/\${_lingtu_video_multiarch}:\${_lingtu_video_prefix}/lib\${LD_LIBRARY_PATH:+:\${LD_LIBRARY_PATH}}"
export GST_PLUGIN_PATH="\${_lingtu_video_prefix}/lib/\${_lingtu_video_multiarch}/gstreamer-1.0:\${_lingtu_video_prefix}/lib/gstreamer-1.0"
export GST_PLUGIN_SYSTEM_PATH_1_0=""
export GST_PLUGIN_SCANNER="\${_lingtu_video_prefix}/libexec/gstreamer-1.0/gst-plugin-scanner"
export GST_PLUGIN_SCANNER_1_0="\${GST_PLUGIN_SCANNER}"
export GST_REGISTRY="\${LINGTU_VIDEO_GST_REGISTRY:-\${XDG_CACHE_HOME:-\${HOME}/.cache}/lingtu/video/gst-registry.bin}"
unset _lingtu_video_multiarch _lingtu_video_prefix
EOF
  printf '%s\n' "${RUNTIME_ARCH}" > "${PREFIX}/runtime-arch"
}

if [[ "${1:-}" == "--refresh-env" ]]; then
  if [[ ! -d "${PREFIX}/lib/${MULTIARCH}" ]]; then
    echo "Prepared camera-video runtime is missing: ${PREFIX}/lib/${MULTIARCH}" >&2
    exit 2
  fi
  write_runtime_metadata
  echo "Refreshed relocatable camera-video runtime metadata: ${PREFIX}"
  exit 0
fi

command -v git >/dev/null
command -v pkg-config >/dev/null

mkdir -p "${SRC}" "${BUILD}" "${PREFIX}"

TOOL_ROOT="${LINGTU_VIDEO_TOOLS_ROOT:-${CACHE_ROOT}/tools}"
MESON_BIN="${MESON_BIN:-${TOOL_ROOT}/bin/meson}"
if [[ ! -x "${MESON_BIN}" || ! -x "${TOOL_ROOT}/bin/ninja" ]] || \
   [[ "$(${MESON_BIN} --version)" != "${MESON_VERSION}" ]] || \
   [[ "$("${TOOL_ROOT}/bin/python" -c 'from importlib.metadata import version; print(version("ninja"))')" != "${NINJA_VERSION}" ]]; then
  python3 -m venv "${TOOL_ROOT}"
  "${TOOL_ROOT}/bin/python" -m pip install --disable-pip-version-check --no-input \
    "meson==${MESON_VERSION}" "ninja==${NINJA_VERSION}"
  MESON_BIN="${TOOL_ROOT}/bin/meson"
fi
export PATH="${TOOL_ROOT}/bin:${PATH}"

# gst-plugins-rs 0.15.4 requires Rust >= 1.92 and cargo-c >= 0.9.21.
# Keep this toolchain isolated from the user's default Rust installation.
RUST_ROOT="${LINGTU_VIDEO_RUST_ROOT:-${CACHE_ROOT}/rust}"
export RUSTUP_HOME="${RUST_ROOT}/rustup"
export CARGO_HOME="${RUST_ROOT}/cargo"
export PATH="${CARGO_HOME}/bin:${PATH}"
export RUSTUP_TOOLCHAIN="${RUST_VERSION}"
if [[ ! -x "${CARGO_HOME}/bin/cargo" || ! -x "${CARGO_HOME}/bin/rustc" ]]; then
  curl --fail --silent --show-error https://sh.rustup.rs | sh -s -- -y --no-modify-path --profile minimal --default-toolchain "${RUST_VERSION}"
  export PATH="${CARGO_HOME}/bin:${PATH}"
fi
if ! "${CARGO_HOME}/bin/rustup" run "${RUST_VERSION}" rustc --version >/dev/null 2>&1; then
  "${CARGO_HOME}/bin/rustup" toolchain install "${RUST_VERSION}" --profile minimal
fi
"${CARGO_HOME}/bin/cargo" --version >/dev/null
export CARGO_BUILD_JOBS="${LINGTU_BUILD_JOBS:-2}"
if [[ ! -x "${CARGO_HOME}/bin/cargo-cbuild" ]] || \
   [[ "$("${CARGO_HOME}/bin/cargo-cbuild" --version)" != "cargo-c ${CARGO_C_VERSION}"* ]]; then
  cargo install cargo-c --version "${CARGO_C_VERSION}" --locked --force \
    --target-dir "${CACHE_ROOT}/cargo-c-build"
fi

clone_at() {
  local url="$1" dir="$2" commit="$3"
  if [[ ! -d "${dir}/.git" ]]; then
    mkdir -p "${dir}"
    git -C "${dir}" init -q
    git -C "${dir}" remote add origin "${url}"
  fi
  git -C "${dir}" fetch --depth=1 origin "${commit}"
  git -C "${dir}" checkout --detach "${commit}"
}

clone_at https://gitlab.freedesktop.org/gstreamer/gstreamer.git "${SRC}/gstreamer-${GST_VERSION}" "${GST_COMMIT}"
clone_at https://gitlab.freedesktop.org/gstreamer/gst-plugins-rs.git "${SRC}/gst-plugins-rs-${RS_VERSION}" "${RS_COMMIT}"
cp "${ROOT}/scripts/build/locks/video-cargo.lock" "${SRC}/gst-plugins-rs-${RS_VERSION}/Cargo.lock"

GST_BUILD="${BUILD}/gstreamer-${GST_VERSION}"
if [[ ! -d "${SRC}/gstreamer-${GST_VERSION}/subprojects/libnice" ]]; then
  "${MESON_BIN}" subprojects download libnice --sourcedir "${SRC}/gstreamer-${GST_VERSION}"
fi
GST_SETUP_ARGS=()
if [[ -f "${GST_BUILD}/meson-private/coredata.dat" ]]; then
  GST_SETUP_ARGS+=(--reconfigure)
fi
"${MESON_BIN}" setup "${GST_SETUP_ARGS[@]}" "${GST_BUILD}" "${SRC}/gstreamer-${GST_VERSION}" \
    --prefix="${PREFIX}" \
    --buildtype=release \
    --force-fallback-for=nice \
    -Dauto_features=disabled \
    -Dgstreamer:tools=enabled \
    -Dgstreamer:check=enabled \
    -Dlibnice=enabled \
    -Dlibnice:gstreamer=enabled \
    -Dbase=enabled -Dgood=enabled -Dugly=enabled \
    -Dgst-plugins-base:app=enabled \
    -Dgst-plugins-base:videoconvertscale=enabled \
    -Dgst-plugins-base:videorate=enabled \
    -Dgst-plugins-good:rtp=enabled \
    -Dgst-plugins-good:rtpmanager=enabled \
    -Dbad=enabled \
    -Dgst-plugins-bad:rtp=enabled \
    -Dgst-plugins-bad:debugutils=enabled \
    -Dgst-plugins-bad:dtls=enabled \
    -Dgst-plugins-bad:srtp=enabled \
    -Dgst-plugins-bad:webrtc=enabled \
    -Dgst-plugins-bad:sctp=enabled \
    -Dgst-plugins-bad:videoparsers=enabled \
    -Dgst-plugins-good:doc=disabled \
    -Dgst-plugins-base:doc=disabled \
    -Dgst-plugins-bad:doc=disabled \
    -Dgst-plugins-ugly:doc=disabled \
    -Dgst-plugins-good:tests=disabled \
    -Dgst-plugins-base:tests=disabled \
    -Dgst-plugins-bad:tests=disabled \
    -Dgst-plugins-ugly:tests=disabled \
    -Dgst-plugins-ugly:x264=enabled \
    -Dx264:asm=enabled \
    -Dgpl=enabled
"${MESON_BIN}" compile -C "${GST_BUILD}" -j "${LINGTU_BUILD_JOBS:-2}"
"${MESON_BIN}" install -C "${GST_BUILD}"

RS_BUILD="${BUILD}/gst-plugins-rs-${RS_VERSION}"
export PKG_CONFIG_PATH="${PREFIX}/lib/${MULTIARCH}/pkgconfig:${PREFIX}/lib/pkgconfig:${PKG_CONFIG_PATH:-}"
RS_CARGO_ARGS=(--locked --release --target-dir "${RS_BUILD}/target"
  --manifest-path "${SRC}/gst-plugins-rs-${RS_VERSION}/Cargo.toml"
  --prefix "${PREFIX}" --libdir "${PREFIX}/lib/${MULTIARCH}"
  -p gst-plugin-rtp -p gst-plugin-webrtc)
# Match upstream Meson's GLib feature selection without its unlocked wrapper.
for glib_version in 2.74 2.72 2.70 2.68 2.66 2.64 2.62 2.60 2.58; do
  if pkg-config --atleast-version="${glib_version}" glib-2.0; then
    glib_feature="${glib_version//./_}"
    RS_CARGO_ARGS+=(--features "gio/v${glib_feature},glib/v${glib_feature}")
    break
  fi
done
(
  cd "${SRC}/gst-plugins-rs-${RS_VERSION}"
  cargo cbuild "${RS_CARGO_ARGS[@]}"
  cargo cinstall "${RS_CARGO_ARGS[@]}"
)

PLUGIN_PATH="${PREFIX}/lib/${MULTIARCH}/gstreamer-1.0:${PREFIX}/lib/gstreamer-1.0"
LIB_PATH="${PREFIX}/lib/${MULTIARCH}:${PREFIX}/lib"
for element in whepserversink rtpgccbwe queue capsfilter appsrc appsink clocksync funnel errorignore videoconvert videoscale videorate h264parse rtph264pay webrtcbin rtpbin rtpfunnel rtprtxsend rtpulpfecenc rtpredenc dtlsenc dtlsdec dtlssrtpenc dtlssrtpdec dtlssrtpdemux srtpenc srtpdec nicesrc nicesink x264enc; do
  GST_PLUGIN_PATH="${PLUGIN_PATH}" GST_PLUGIN_SYSTEM_PATH_1_0="" GST_REGISTRY="${PREFIX}/gst-registry.bin" \
    LD_LIBRARY_PATH="${LIB_PATH}${LD_LIBRARY_PATH:+:${LD_LIBRARY_PATH}}" \
    "${PREFIX}/bin/gst-inspect-1.0" "${element}" >/dev/null
done

write_runtime_metadata
ENV_FILE="${PREFIX}/env.sh"
cat <<EOF
Prepared isolated camera-video dependencies.
ENV_FILE=${ENV_FILE}
GST_PLUGIN_PATH=${PLUGIN_PATH}
LD_LIBRARY_PATH=${LIB_PATH}
GST_PLUGIN_SYSTEM_PATH_1_0=
EOF
